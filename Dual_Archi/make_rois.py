#!/usr/bin/env python3
"""
make_rois.py -- generate pot_rois.json for the 3x3 Pechay array.

The ROI file shipped with v3 was a placeholder and was not physically possible:
its x-pitch was 700 px and its y-pitch 390 px, which cannot both be true for a
square array viewed from nadir, and its 520x360 px boxes worked out to roughly
396 x 280 mm against a 200 mm pot. Every GPR computed from it would have been
wrong. This tool replaces guesswork with either measured pixels or geometry.

TWO MODES
---------
1. --from-centers  (PREFERRED, use once the rig is standing)
   Capture one frame with all nine pots in place, open it in any image viewer,
   read off the pixel coordinates of the centre of the top-left pot and the
   centre of the bottom-right pot, and measure one pot's rim diameter in pixels.
   Everything else is interpolated. This absorbs real lens distortion, a
   slightly off-square bench and a camera that is not perfectly centred.

       python3 make_rois.py --from-centers --tl 610 130 --br 1690 1160 \
                            --pot-px 260 -o pot_rois.json

2. --from-geometry  (planning only, before the rig exists)
   Predicts the grid from mount height and physical dimensions. Use it to sanity
   check framing and to have a file that lets the pipeline run in test mode.

       python3 make_rois.py --from-geometry --height-mm 1350 -o pot_rois.json

GUARD MARGIN
------------
Section III.C requires the ROI to sit INSIDE the pot rim with a guard margin,
so a leaf crossing from a neighbour cannot enter this pot's count. --guard is
the fraction of the rim diameter trimmed off; 0.10 (default) means the ROI is
90 % of the rim.
"""

import argparse
import json
import math

POT_IDS = [f"P-0{i}" for i in range(1, 10)]     # row-major: P-01..P-03 = top row


def from_centers(tl, br, pot_px, guard):
    x0, y0 = tl
    x1, y1 = br
    side = int(round(pot_px * (1.0 - guard)))
    rois = {}
    for r in range(3):
        for c in range(3):
            cx = round(x0 + (x1 - x0) * c / 2.0)
            cy = round(y0 + (y1 - y0) * r / 2.0)
            rois[POT_IDS[r * 3 + c]] = {"x": int(cx - side // 2),
                                        "y": int(cy - side // 2),
                                        "w": side, "h": side}
    return rois


def from_geometry(height_mm, pitch_mm, pot_mm, frame, hfov, vfov, guard):
    fw, fh = frame
    cov_w = 2 * height_mm * math.tan(math.radians(hfov / 2))
    cov_h = 2 * height_mm * math.tan(math.radians(vfov / 2))
    pxmm_x, pxmm_y = fw / cov_w, fh / cov_h

    span_mm = 2 * pitch_mm                       # centre of TL pot to centre of BR
    if span_mm * pxmm_y + pot_mm * pxmm_y > fh:
        raise SystemExit(
            f"array does not fit vertically at {height_mm:.0f} mm: needs "
            f"{(span_mm + pot_mm) * pxmm_y:.0f} px of {fh} px. Raise the camera.")

    tl = (fw / 2 - span_mm * pxmm_x / 2, fh / 2 - span_mm * pxmm_y / 2)
    br = (fw / 2 + span_mm * pxmm_x / 2, fh / 2 + span_mm * pxmm_y / 2)
    pot_px = pot_mm * min(pxmm_x, pxmm_y)
    meta = {"px_per_mm_x": round(pxmm_x, 4), "px_per_mm_y": round(pxmm_y, 4),
            "coverage_mm": [round(cov_w), round(cov_h)],
            "pot_px": round(pot_px)}
    return from_centers(tl, br, pot_px, guard), meta


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--from-centers", action="store_true")
    ap.add_argument("--tl", nargs=2, type=float, metavar=("X", "Y"))
    ap.add_argument("--br", nargs=2, type=float, metavar=("X", "Y"))
    ap.add_argument("--pot-px", type=float)

    ap.add_argument("--from-geometry", action="store_true")
    ap.add_argument("--height-mm", type=float, default=1350.0)
    ap.add_argument("--pitch-mm", type=float, default=350.0)
    ap.add_argument("--pot-mm", type=float, default=200.0)
    ap.add_argument("--hfov", type=float, default=66.0)   # Camera Module 3 std
    ap.add_argument("--vfov", type=float, default=41.0)

    ap.add_argument("--frame", nargs=2, type=int, default=[2304, 1296])
    ap.add_argument("--guard", type=float, default=0.10)
    ap.add_argument("--circular", action="store_true", default=True)
    ap.add_argument("-o", "--out", default="pot_rois.json")
    args = ap.parse_args()

    meta = {}
    if args.from_centers:
        if not (args.tl and args.br and args.pot_px):
            raise SystemExit("--from-centers needs --tl, --br and --pot-px")
        rois = from_centers(args.tl, args.br, args.pot_px, args.guard)
        source = "measured centers"
    else:
        rois, meta = from_geometry(args.height_mm, args.pitch_mm, args.pot_mm,
                                   args.frame, args.hfov, args.vfov, args.guard)
        source = "predicted from geometry -- RE-RUN WITH --from-centers ONCE THE RIG IS UP"

    doc = {
        "_comment": "Generated by make_rois.py. Do not hand-edit.",
        "_source": source,
        "_frame": args.frame,
        "_guard_fraction": args.guard,
        "_meta": meta,
        "circular": bool(args.circular),
        "rois": rois,
    }
    with open(args.out, "w") as f:
        json.dump(doc, f, indent=2)

    print(f"wrote {args.out}  ({source})")
    for k, v in rois.items():
        print(f"  {k}  x={v['x']:5d} y={v['y']:5d}  {v['w']}x{v['h']}")


if __name__ == "__main__":
    main()
